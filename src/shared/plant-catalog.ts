/**
 * Library of common houseplants, used to pre-fill a plant's page.
 *
 * Watering rhythms are indicative ("every N days" in summer / in winter): actual needs depend
 * on the pot, the substrate, the light and the heating. Toxicity notes concern cats and dogs.
 */
import type { Exposure, Humidity } from '../domain/plant.ts'

export type CatalogPlant = {
  id: string
  name: string
  aliases: string[]
  scientificName: string
  /** Wikipedia page to illustrate the plant, when the scientific name does not lead to one. */
  wiki?: string
  description: string
  care: { exposure: Exposure; humidity: Humidity; temperature: string; watering: string; notes?: string }
  rhythm: { summerEveryDays: number; winterEveryDays: number }
}

const SUN: Exposure = 'direct-sun'
const BRIGHT: Exposure = 'bright-indirect'
const HALF: Exposure = 'partial-shade'
const SHADE: Exposure = 'shade'

const TOXIC = 'Toxique pour les chats et les chiens.'
const TOXIC_ARACEAE = 'Toxique pour les chats et les chiens (cristaux d’oxalate de calcium).'
const TOXIC_LATEX = 'Sève irritante, toxique pour les chats et les chiens.'

function plant(
  id: string,
  name: string,
  scientificName: string,
  exposure: Exposure,
  humidity: Humidity,
  temperature: string,
  [summerEveryDays, winterEveryDays]: [number, number],
  watering: string,
  description: string,
  extra: { aliases?: string[]; notes?: string; wiki?: string } = {},
): CatalogPlant {
  return {
    id,
    name,
    aliases: extra.aliases ?? [],
    scientificName,
    ...(extra.wiki ? { wiki: extra.wiki } : {}),
    description,
    care: { exposure, humidity, temperature, watering, ...(extra.notes ? { notes: extra.notes } : {}) },
    rhythm: { summerEveryDays, winterEveryDays },
  }
}

